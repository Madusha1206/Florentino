const item = (category, folder, filename, price) => ({
  code: filename.replace(/\.[^.]+$/, ''),
  category,
  image: `/images/${folder}/${filename}`,
  ...(price === undefined ? {} : { price }),
});

const fromFiles = (category, folder, files, prices = {}) =>
  files.map((filename) => item(category, folder, filename, prices[filename.replace(/\.[^.]+$/, '')]));

